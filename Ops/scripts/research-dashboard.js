#!/usr/bin/env node

/**
 * Allternit Brain — research pipeline dashboard
 *
 * Regenerates Research/Dashboard.md from Research/queue.json: the human's
 * gate view of the pipeline. Actionable statuses come first, then newest
 * entries within each status. Run at the end of every pipeline sweep.
 *
 * Usage:
 *   node research-dashboard.js [--queue <path>] [--out <path>]
 *
 * Defaults derive from the script's location, not cwd. Prints a one-line
 * summary.
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const BRAIN_ROOT = path.resolve(__dirname, '..', '..');
const DEFAULT_QUEUE = path.join(BRAIN_ROOT, 'Research', 'queue.json');
const DEFAULT_OUT = path.join(BRAIN_ROOT, 'Research', 'Dashboard.md');

const NEXT_ACTION = {
  inbox: 'awaiting research',
  researched: 'needs spec',
  spec_ready: 'AWAITING HUMAN GATE',
  approved: 'ready to spawn executor',
  executing: 'executor running',
  pr_open: 'review PR',
  quarantined: 'quarantined — human recovery required',
  landed: 'done',
  watch: 'watchlist only',
  rejected: '—',
};

// Lower numbers sort first: actionable pipeline states at the top.
const STATUS_ORDER = [
  'spec_ready',
  'approved',
  'executing',
  'pr_open',
  'quarantined',
  'inbox',
  'researched',
  'landed',
  'watch',
  'rejected',
];

// Decision-steward inputs for a gate item: the queue decision field plus the
// spec's "## Open questions" bullets (verbatim, capped). Read failures skip.
function decisionsNeeded(item) {
  const out = [];
  if (item.decision) out.push(`decision: ${item.decision}`);
  if (item.spec) {
    try {
      const abs = path.isAbsolute(item.spec)
        ? item.spec
        : path.join(BRAIN_ROOT, item.spec);
      const text = fs.readFileSync(abs, 'utf8');
      const m = text.match(/^## Open questions$([\s\S]*?)(?=^## |\n*$(?![\s\S]))/m);
      if (m) {
        const bullets = m[1]
          .split('\n')
          .map((l) => l.trim())
          .filter((l) => l.startsWith('- '))
          .map((l) => l.slice(2))
          .slice(0, 4);
        out.push(...bullets);
      }
    } catch (e) {
      // unreadable spec — fall through with whatever we have
    }
  }
  return out;
}

function argValue(args, flag, fallback) {
  const idx = args.indexOf(flag);
  return idx !== -1 ? args[idx + 1] : fallback;
}

function today() {
  return new Date().toISOString().slice(0, 10);
}

function esc(text) {
  return String(text ?? '').replace(/\|/g, '\\|');
}

function lastTs(item) {
  const history = item.history || [];
  return history.length ? history[history.length - 1].ts : '';
}

function main() {
  const args = process.argv.slice(2);
  const queuePath = argValue(args, '--queue', DEFAULT_QUEUE);
  const outPath = argValue(args, '--out', DEFAULT_OUT);

  if (!fs.existsSync(queuePath)) {
    console.error(`Queue not found: ${queuePath}`);
    process.exit(1);
  }

  const queue = JSON.parse(fs.readFileSync(queuePath, 'utf8'));
  const items = [...(queue.items || [])].sort((a, b) => {
    const da = STATUS_ORDER.indexOf(a.status);
    const db = STATUS_ORDER.indexOf(b.status);
    if (da !== db) return (da === -1 ? 99 : da) - (db === -1 ? 99 : db);
    return lastTs(b).localeCompare(lastTs(a));
  });

  const counts = {};
  for (const item of items) counts[item.status] = (counts[item.status] || 0) + 1;

  const lines = [
    '---',
    'doc: index',
    `updated: ${today()}`,
    'status: active',
    '---',
    '',
    '# Research — Pipeline Dashboard',
    '',
    'Regenerated by `Ops/scripts/research-dashboard.js` from [`queue.json`](queue.json) — do not edit by hand. Human gate: `spec_ready` rows need explicit approval before any executor is spawned.',
    '',
    `| id | item | status | spec | next action |`,
    `|---|---|---|---|---|`,
  ];

  for (const item of items) {
    const label = item.title || item.url;
    const itemCell = item.url ? `[${esc(label)}](${item.url})` : esc(label);
    let specCell = '—';
    if (item.spec) {
      const rel = String(item.spec).replace(/^Research\//, '');
      const abs = path.isAbsolute(item.spec)
        ? item.spec
        : path.join(BRAIN_ROOT, item.spec);
      if (fs.existsSync(abs)) {
        specCell = `[${esc(path.basename(item.spec))}](${rel})`;
      } else {
        // Do not claim a phantom path exists — show missing marker
        specCell = `missing:${esc(path.basename(item.spec))}`;
      }
    }
    const action = NEXT_ACTION[item.status] || '—';
    lines.push(
      `| ${esc(item.id)} | ${itemCell} | ${esc(item.status)} | ${specCell} | ${action} |`
    );
  }

  lines.push('', `_${items.length} item(s): ${STATUS_ORDER.filter((s) => counts[s]).map((s) => `${s} ${counts[s]}`).join(', ')}._`, '');

  const gateItems = items.filter((item) => item.status === 'spec_ready');
  if (gateItems.length > 0) {
    lines.push('## Approvals', '');
    lines.push('Each `spec_ready` item needs explicit human approval before an executor is spawned. Three equivalent paths:');
    for (const item of gateItems) {
      const slug = path.basename(String(item.spec || '')).replace(/\.md$/i, '') || item.id;
      lines.push(`- \`${slug}\``);
      lines.push(`  - MCP: \`research_approve\` with slug \`${slug}\``);
      lines.push(`  - CLI: \`node Ops/scripts/research-approve.js ${slug}\``);
      lines.push(`  - File: drop \`Research/gate/approvals/${slug}.approve\` and run \`node Ops/scripts/research-approve.js --consume-all\``);
      const decisions = decisionsNeeded(item);
      if (decisions.length > 0) {
        lines.push('  - Decisions needed:');
        for (const d of decisions) lines.push(`    - ${d}`);
      } else {
        lines.push('  - Decisions needed: no open questions recorded');
      }
    }
    lines.push('');
  }

  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, lines.join('\n'));

  console.log(`research-dashboard: ${items.length} item(s) → ${outPath}`);
}

main();
